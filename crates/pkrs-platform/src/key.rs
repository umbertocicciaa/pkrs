#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn all_is_sorted_and_unique() {
        let set: BTreeSet<Key> = Key::ALL.iter().copied().collect();
        assert_eq!(set.len(), Key::ALL.len());
        assert!(Key::ALL.windows(2).all(|w| w[0] < w[1]));
    }
}
